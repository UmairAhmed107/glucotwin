    with open(output_path, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "name",
            "serving_description",
            "carbs",
            "protein",
            "fat",
            "calories",
            "fiber",
            "category",
            "is_demo",
            "disclaimer",
        ])
        for entry in FOOD_ENTRIES:
            writer.writerow([
                entry[0],
                entry[1],
                entry[2],
                entry[3],
                entry[4],
                entry[5],
                entry[6],
                entry[7],
                "true",
                DISCLAIMER,
            ])
    print(f"Generated {len(FOOD_ENTRIES)} food items into {output_path}")

